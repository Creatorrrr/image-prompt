"""Experimental, exact-hash-scoped display projection; NEVER a source migration.

The material and canonical record remain byte-equivalent.  Only explicitly
reviewed research-ID locations in the human-facing compact JSON are aliased.
A consumer must never use a display alias as a native owner/gate selector.
"""
import copy, hashlib, json, re
from pathlib import Path

MARK='[research semantics: optional review metadata, not native adoption authority] '
WARNING=('[identifiers and relation expressions in this block are display projections, not source literals or native selectors] ')

def digest(value):
    return hashlib.sha256(json.dumps(value,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()).hexdigest()

def build_manifest(review_path,delta_path):
    report=json.loads(Path(review_path).read_bytes()); delta=json.loads(Path(delta_path).read_bytes())['candidates']
    inventory=json.loads((Path(__file__).parent/'approved-source-inventory.json').read_bytes())
    reviewed={row['candidate_id']:row for row in inventory['candidates']}
    if len(reviewed)!=len(inventory['candidates']): raise ValueError('duplicate inventory candidate')
    result={}
    for row in report['decisions']:
        if row['additional_decision']!='retain_effective': continue
        record=row['full_effective_after'] or delta[row['candidate_id']]['after']
        if digest(record)!=row['effective_after_sha256']: raise ValueError('review source mismatch')
        found=[x for x in row['occurrences'] if x['classification']=='internal_identifier' and x['actually_displayed_by_static_v3_selection']]
        if found:
            approved=reviewed.get(row['candidate_id'])
            if not approved or approved['source_sha256']!=digest(record) or approved['reviewed_inventory']!=found:
                raise ValueError('review inventory differs from exact source')
            result[row['candidate_id']]={'sha256':digest(record),'pointers':found,
                'additional_sites':approved['additional_identifier_sites']}
    if set(result)!=set(reviewed): raise ValueError('review inventory coverage changed')
    return result

def alias(cid, text, namespace):
    return namespace+'_'+hashlib.sha256(('photo-display-alias/v1\0'+cid+'\0'+text).encode()).hexdigest()[:16]

def transform(value,cid,is_gate=False):
    if is_gate: return alias(cid,value,'gate')
    return re.sub(r'(?<![A-Za-z0-9_])adult(?![A-Za-z0-9_])',alias(cid,'adult','owner'),value)

def project(material,record,manifest,*,issued_material=None):
    """Return copy, with projections only when exact reviewed native source matches.

    Untouched records, explicit adult conditions and positive meanings containing
    adult are returned verbatim. Source, proof and conditions are never changed.
    """
    cid=record['id']; spec=manifest.get(cid); out=copy.deepcopy(material)
    if not spec: return out,{'state':'unchanged_unmatched'}
    if digest(record)!=spec['sha256']: raise ValueError('reviewed candidate source hash changed')
    # This argument must be generated by the trusted receipt-verified caller,
    # not provided by the person or model requesting a projection.
    if issued_material is None or material!=issued_material:
        raise ValueError('receipt-verified issued material required')
    if material.get('candidate_id')!=cid or material.get('conditions')!=record.get('conditions'):
        raise ValueError('material candidate or conditions differ from source')
    if re.search(r'(?i)adult|성인',json.dumps(record.get('conditions',{}),ensure_ascii=False)):return out,{'state':'unchanged_explicit_age_condition'}
    primary=' '.join(str(record['content'].get(k,'')) for k in ('en','ko','definition'))
    if re.search(r'(?i)\badult\b|성인',primary):return out,{'state':'unchanged_explicit_age_meaning'}
    # v4 explicitly authorizes only the identifier token inside reviewed,
    # source-bound relation expressions; the surrounding text is unchanged.
    lines=out['meaning'].split('\n'); positions=[i for i,v in enumerate(lines) if v.startswith(MARK)]
    if len(positions)!=1:raise ValueError('one research metadata block required')
    index=positions[0];research=json.loads(lines[index][len(MARK):]); pending=[];renames=[];aliases={};sites=[]
    # Verify the entire displayed research block against the hash-bound source,
    # not just the old inventory's individual pointers.
    from photo_h_f2_workflow import RESEARCH_MEANING_FIELDS
    native_research=record['content'].get('research_semantics',{})
    expected={k:v for k,v in native_research.items() if k in RESEARCH_MEANING_FIELDS and v not in (None,[],{},'')}
    for k in ('positive_en','positive_ko','proposal_en','proposal_ko','phrase_en','phrase_ko','visible_en','visible_ko'):
        if isinstance(expected.get(k),str) and expected[k] in lines[:index]:del expected[k]
    if research!=expected: raise ValueError('display research differs from source')
    def register(original,display,namespace):
        prior=aliases.get(display)
        if prior is not None and prior!=original: raise ValueError('display alias collision')
        aliases[display]=original
    register('adult',alias(cid,'adult','owner'),'owner')
    for occ in spec['pointers']:
        path=occ['pointer'].split('/')[3:];cur=research
        for bit in path[:-1]:cur=cur[int(bit)] if isinstance(cur,list) else cur[bit.replace('~1','/').replace('~0','~')]
        key=path[-1].replace('~1','/').replace('~0','~');key=int(key) if isinstance(cur,list) else key
        if occ['kind']=='object_key':
            if key not in cur:raise ValueError('reviewed object key missing')
            new=transform(key,cid);renames.append((cur,key,new))
        else:
            old=cur[key]
            if old!=occ['effective_value']:raise ValueError('reviewed value changed')
            new=transform(old,cid,is_gate=key=='gate_id')
            if key=='gate_id': register(old,new,'gate')
            if new==old:raise ValueError('reviewed identifier not projected')
            pending.append((cur,key,old,new))
    for cur,key,old,new in pending:cur[key]=new
    for cur,old,new in renames:
        if new in cur and new!=old:raise ValueError('display alias collision')
        cur[new]=cur.pop(old)
    # Additional structured slots discovered in the final hash-bound source.
    # Only identifiers are changed; descriptive values and conditions are not.
    def extend(obj,path=()):
        if isinstance(obj,list):
            for i,v in enumerate(obj): extend(v,path+(str(i),))
        elif isinstance(obj,dict):
            for k,v in list(obj.items()):
                p=path+(k,); pointer='/content/research_semantics/'+ '/'.join(x.replace('~','~0').replace('/','~1') for x in p)
                owner_slot=k in ('owner','subject','object','from','to') or (k=='id' and len(path)>=2 and path[-2]=='owners')
                gate_slot=(k=='gate_id' or (k=='id' and len(path)>=2 and path[-2]=='render_gate_proposals'))
                if isinstance(v,str) and owner_slot and v=='adult':
                    obj[k]=alias(cid,'adult','owner');sites.append({'pointer':pointer,'before':v,'after':obj[k]})
                elif isinstance(v,str) and gate_slot and re.search('adult',v,re.I):
                    new=alias(cid,v,'gate');register(v,new,'gate');obj[k]=new;sites.append({'pointer':pointer,'before':v,'after':new})
                else:extend(v,p)
    # The reviewed inventory may precede later owner-reference repairs.  Never
    # emit a partly aliased graph: a remaining age token could be an unlisted
    # reference, or genuine semantics which this projection must not rewrite.
    extend(research)
    normalize=lambda rows: sorted((x['pointer'],x['before'],x['after']) for x in rows)
    if normalize(sites)!=normalize(spec['additional_sites']):
        raise ValueError('additional identifier sites differ from reviewed inventory')
    if re.search(r'(?i)adult|성인',json.dumps(research,ensure_ascii=False)):
        raise ValueError('unreviewed age token in projected research block')
    # Aliases must not already denote a different source identifier or string.
    source_serialized=json.dumps(expected,ensure_ascii=False)
    if any(x in source_serialized for x in aliases):raise ValueError('alias exists in source')
    lines[index]=MARK+WARNING+json.dumps(research,ensure_ascii=False,sort_keys=True,separators=(',',':'))
    out['meaning']='\n'.join(lines)
    return out,{'state':'projected','count':len(spec['pointers']),'source_sha256':spec['sha256'],'alias_scope':'display_only_not_native_selector','reverse_aliases':aliases,'additional_sites':sites}
